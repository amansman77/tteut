export interface HanjaChar {
  char: string;
  reading: string;
  meaning: string;
}

export function parseHanja(origin: string): HanjaChar[] {
  return [...origin].flatMap((ch) => {
    const entry = HANJA[ch];
    if (!entry) return [];
    return [{ char: ch, meaning: entry[0], reading: entry[1] }];
  });
}
